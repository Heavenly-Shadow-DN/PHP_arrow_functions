<?php
// Задача 2. Захват переменных из внешней области

$discount = 0.9; // скидка 10%

$applyDiscount = fn(float $price): float => $price * $discount;

// применяем к нескольким ценам
echo $applyDiscount(1000), "\n"; // 900
echo $applyDiscount(250), "\n";  // 225
echo $applyDiscount(80), "\n";   // 72

// меняем внешнюю переменную ПОСЛЕ создания функции
$discount = 0.5;
echo $applyDiscount(1000), "\n"; // всё равно 900, а не 500

/*
Почему результат не изменился: стрелочная функция fn захватывает внешние
переменные автоматически, по значению и в момент создания функции.
То есть внутри fn лежит копия $discount = 0.9, сделанная при объявлении.
Позднее изменение $discount на 0.5 на эту копию никак не влияет.
*/

// функция, использующая сразу две внешние переменные
$rate = 90.5; // курс доллара к рублю
$toRubles = fn(float $usd): float => $usd * $rate * $discount;

echo $toRubles(10), "\n"; // 10 * 90.5 * 0.5 = 452.5 ($discount уже равна 0.5 на момент создания $toRubles)

/*
Вывод в терминале:
900
225
72
900
452.5
*/
